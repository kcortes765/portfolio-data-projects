"""Deterministic, fictional operations documents. No real customer data."""
import csv,io,json,hashlib,random
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FIELDS=['kind','entity_id','order_id','version','amount_minor','currency','quantity','unit','event_date']

def generate():
    rng=random.Random(20260912); base=[]; late=[]; orders={}
    def event(kind,i,amount,currency,quantity,unit,version=1,suffix=''):
        return dict(kind=kind,entity_id=f'{kind[0].upper()}-{i:04d}{suffix}',order_id=f'PED-{i:04d}',version=str(version),amount_minor=str(amount),currency=currency,quantity=str(quantity),unit=unit,event_date=f'2026-08-{(i-1)%24+1:02d}')
    for i in range(1,25):
        currency='USD' if i%6==0 else 'CLP'; unit='kg' if i%5==0 else 'ea'; quantity=i%7+2
        amount=quantity*(1200+i*10 if currency=='USD' else 8500+rng.randrange(20)*100)
        order=event('order',i,amount,currency,quantity,unit); orders[i]=order; base.append(order)
        inv=event('invoice',i,amount,currency,quantity,unit)
        if i in [3,9,15]:late.append(inv)
        elif i==24:
            base.extend([event('invoice',i,amount//2,currency,quantity,unit,suffix='A'),event('invoice',i,amount-amount//2,currency,quantity,unit,suffix='B')])
        else:
            if i==5:inv['amount_minor']=str(amount+500);late.append(event('invoice',i,amount,currency,quantity,unit,2))
            if i==7:inv['currency']='USD';late.append(event('invoice',i,amount,currency,quantity,unit,2))
            base.append(inv)
        delivery=event('delivery',i,0,currency,quantity,unit)
        if i in [4,9,17]:late.append(delivery)
        else:
            if i==11:delivery['unit']='kg';late.append(event('delivery',i,0,currency,quantity,unit,2))
            if i==13:delivery['quantity']=str(quantity-1);late.append(event('delivery',i,0,currency,quantity,unit,2))
            if i==19:delivery['quantity']=str(quantity+1);late.append(event('delivery',i,0,currency,quantity,unit,2))
            base.append(delivery)
    base.extend([dict(base[i]) for i in [0,1,2,8]])
    base.append(event('invoice',999,45000,'CLP',5,'ea'))
    late.extend([event('order',999,45000,'CLP',5,'ea'),event('delivery',999,0,'CLP',5,'ea')])
    base.extend([event('delivery',800,0,'CLP',-2,'ea'),event('invoice',801,900,'EUR',1,'ea')])
    conflict=[dict(base[1],amount_minor='999999')]
    definitions=[('base','Carga inicial',base,FIELDS),('late','Llegadas y correcciones',late,FIELDS),('conflict','Conflicto de versión',conflict,FIELDS),('schema','Esquema incompatible',[base[0]],[x for x in FIELDS if x!='currency'])]
    bundle={}; public=ROOT/'public/opsforge/fixtures'; public.mkdir(parents=True,exist_ok=True)
    for name,label,rows,fields in definitions:
        out=io.StringIO(newline='');writer=csv.DictWriter(out,fieldnames=fields,lineterminator='\n',extrasaction='ignore');writer.writeheader();writer.writerows(rows)
        content=out.getvalue();sha=hashlib.sha256(content.encode()).hexdigest();file=f'{name}-{sha[:12]}.csv'
        (public/file).write_text(content,encoding='utf8',newline='\n')
        bundle[name]=dict(id=name,label=label,file=file,sha256=sha,csv=content,rows=len(rows))
    result=dict(seed=20260912,synthetic=True,description='Documentos ficticios; importes netos sin impuestos ni conversión de moneda.',fields=FIELDS,batches=bundle)
    (ROOT/'lib/opsforge').mkdir(parents=True,exist_ok=True)
    (ROOT/'lib/opsforge/fixtures.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    manifest={k:{a:v for a,v in b.items() if a!='csv'} for k,b in bundle.items()}
    (public/'manifest.json').write_text(json.dumps(dict(seed=result['seed'],synthetic=True,batches=manifest),ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    # Oracle comes from deliberately specified order-level cases, not reconciliation SQL.
    expected=dict(initial_orders=24,final_orders=25,initial_open_orders=[f'PED-{i:04d}' for i in [3,4,5,7,9,11,13,15,17,19]],final_open_orders=[],initial_quarantined=2,initial_duplicates=4,initial_orphans=1)
    (ROOT/'opsforge/expected.json').write_text(json.dumps(expected,indent=2)+'\n')
    sql=(ROOT/'opsforge/reconciliation.sql').read_text().replace(':scope','?')
    (ROOT/'lib/opsforge/sql.ts').write_text('// Generated by opsforge/generate.py; edit reconciliation.sql.\nexport const reconciliationSql='+json.dumps(sql)+';\n',encoding='utf8')
    print(json.dumps({k:b['rows'] for k,b in bundle.items()}))
if __name__=='__main__':generate()
